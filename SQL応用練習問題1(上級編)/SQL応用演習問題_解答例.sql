-- 社員マスタ
CREATE TABLE IF NOT EXISTS EMPLOYEE (
    NUMBER INT PRIMARY KEY,
    NAME VARCHAR(50),
    DEPT_ID VARCHAR(10)
);

-- 部署マスタ
CREATE TABLE IF NOT EXISTS DEPARTMENT (
    DEPT_ID VARCHAR(10) PRIMARY KEY,
    DEPT_NAME VARCHAR(50)
);

-- 給与テーブル
CREATE TABLE IF NOT EXISTS SALARY (
    NUMBER INT PRIMARY KEY,
    AMOUNT INT,
    ALLOWANCE INT
);

