-- ① 部署D002の社員、給与降順
SELECT 
  EMP.NAME
, EMP.DEPT_ID
, SRY.AMOUNT
FROM 
  EMPLOYEE EMP
JOIN
  SALARY SRY
ON 
  EMP.NUMBER = SRY.NUMBER
WHERE 
  EMP.DEPT_ID = 'D002'
ORDER BY
  SRY.AMOUNT DESC;

-- ② 部署D001で給与最大の社員
SELECT
  EMP.NUMBER
, EMP.NAME
, SRY.AMOUNT
FROM 
  EMPLOYEE EMP
JOIN
  SALARY SRY
ON 
  EMP.NUMBER = SRY.NUMBER
WHERE
  EMP.DEPT_ID = 'D001'
AND
  SRY.AMOUNT = (
                 SELECT 
                   MAX(SRY2.AMOUNT) 
                 FROM
                   EMPLOYEE EMP2
                 JOIN
                   SALARY SRY2 
                 ON
                   EMP2.NUMBER = SRY2.NUMBER
                 WHERE
                   EMP2.DEPT_ID = 'D001'
               )
;

-- ③ 部署D003の平均以下
SELECT
  EMP.NUMBER
, EMP.NAME
, SRY.AMOUNT
FROM 
  EMPLOYEE EMP
JOIN
  SALARY SRY
ON 
  EMP.NUMBER = SRY.NUMBER
WHERE
  EMP.DEPT_ID = 'D003'
AND
  SRY.AMOUNT <= (
                  SELECT
                    AVG(SRY2.AMOUNT)
                   FROM
                     EMPLOYEE EMP2
                   JOIN
                     SALARY SRY2 
                   ON 
                     EMP2.NUMBER = SRY2.NUMBER
                   WHERE 
                     EMP2.DEPT_ID = 'D003'
                 )
ORDER BY
  SRY.AMOUNT ASC;

-- ④ 部署ごとの平均給与
SELECT
  EMP.DEPT_ID AS 部署ID
, AVG(SRY.AMOUNT) AS 平均給与
FROM
  EMPLOYEE EMP
JOIN
  SALARY SRY 
ON
  EMP.NUMBER = SRY.NUMBER
GROUP BY
  EMP.DEPT_ID
ORDER BY
  EMP.DEPT_ID ASC;

-- ⑤ 社員ごとの年間総支給額
SELECT
  EMP.NUMBER AS 社員番号
, EMP.NAME AS 氏名
, (SRY.AMOUNT + SRY.ALLOWANCE) * 12 AS 年間総支給額
FROM 
  EMPLOYEE EMP
JOIN
  SALARY SRY 
ON
  EMP.NUMBER = SRY.NUMBER
ORDER BY
  年間総支給額 DESC;

-- ⑥ 部署ごとの総給与額
SELECT E.DEPT_ID AS 部署ID, SUM(S.AMOUNT + S.ALLOWANCE) AS 総給与
FROM EMPLOYEE E
JOIN SALARY S ON E.NUMBER = S.NUMBER
GROUP BY E.DEPT_ID
ORDER BY 総給与 DESC;

-- ⑦ 社員番号昇順で基本給・手当表示
SELECT E.NUMBER, E.NAME, S.AMOUNT AS 基本給, S.ALLOWANCE AS 手当額
FROM EMPLOYEE E
JOIN SALARY S ON E.NUMBER = S.NUMBER
ORDER BY E.NUMBER ASC;

-- ⑧ 部署D002の順位付け（上位5名）※同率5位は切り捨てられる(Oracleは使えない)
SELECT 
  RANK() OVER (ORDER BY SRY.AMOUNT DESC) AS 順位
, EMP.NUMBER AS 社員番号
, EMP.NAME AS 氏名
, EMP.DEPT_ID AS 部署ID
, SRY.AMOUNT AS 給与
FROM
  EMPLOYEE EMP
JOIN
  SALARY SRY
ON
  EMP.NUMBER = SRY.NUMBER
WHERE
  EMP.DEPT_ID = 'D002'
ORDER BY
  順位 ASC
LIMIT 
  5
;
-- ⑧別解(小栁、藤田さんバージョン) ※推奨(Oracle対応版)
SELECT
  順位tbl.順位
, 順位tbl.社員番号
, 順位tbl.氏名
, 順位tbl.部署ID
, 順位tbl.給与
FROM
  (
    SELECT
      RANK() OVER (ORDER BY AMOUNT DESC) AS 順位
    , EMP.NUMBER AS 社員番号
    , EMP.NAME AS 氏名
    , EMP.DEPT_ID AS 部署ID
    , SLR.AMOUNT AS 給与
    FROM
      SALARY SLR
    JOIN 
      EMPLOYEE EMP
    ON
      SLR.NUMBER = EMP.NUMBER
    WHERE
      EMP.DEPT_ID = 'D002'
  ) AS 順位tbl
WHERE 順位tbl.順位 <= 5;

-- ⑧別解(梅本さんバージョン)※覚えておくとよい
WITH RANKED AS (
 SELECT
   RANK() OVER (ORDER BY SAL.AMOUNT DESC) AS 順位
 , EMP.NUMBER AS 社員番号
 , EMP.NAME AS 氏名
 , EMP.DEPT_ID AS 部署ID
 , SAL.AMOUNT AS 給与
 FROM
   EMPLOYEE EMP
 JOIN
   SALARY SAL
 ON
   EMP.NUMBER = SAL.NUMBER
 WHERE
   EMP.DEPT_ID = 'D002'
)
SELECT
  順位
, 社員番号
, 氏名
, 部署ID
, 給与
FROM
  RANKED
WHERE
  順位 <= 5
ORDER BY
  順位 ASC
;
