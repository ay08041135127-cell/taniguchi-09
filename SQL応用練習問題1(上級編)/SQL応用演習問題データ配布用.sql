-- 社員マスタ
CREATE TABLE EMPLOYEE (
    NUMBER INT PRIMARY KEY,
    NAME VARCHAR(50),
    DEPT_ID VARCHAR(10)
);

-- 部署マスタ
CREATE TABLE DEPARTMENT (
    DEPT_ID VARCHAR(10) PRIMARY KEY,
    DEPT_NAME VARCHAR(50)
);

-- 給与テーブル
CREATE TABLE SALARY (
    NUMBER INT,
    AMOUNT INT,
    ALLOWANCE INT,
    PRIMARY KEY (NUMBER)
);
